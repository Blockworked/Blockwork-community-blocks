// Copies how Blockwork's editor lays out each block's row into src/block-rows.ts,
// so the site's source view draws the same blocks, words and icons.
// Usage: node scripts/extract-block-rows.mjs [path to Blockwork] [path to blockstitch]
// (default ../Blockwork and ../blockstitch). Rerun when the editor's blocks change.

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const blockwork = process.argv[2] ?? "../Blockwork";
const blockstitch = process.argv[3] ?? "../blockstitch";
const editor = readFileSync(join(blockwork, "blockwork-qt/qml/EditorPage.qml"), "utf8");
const registry = readFileSync(join(blockstitch, "qml/Blockstitch/BlockRegistry.qml"), "utf8");

/** The text of a `{ ... }` or `[ ... ]` starting at `open`, matched by brackets (strings skipped). */
function balanced(text, open) {
  const pairs = { "{": "}", "[": "]", "(": ")" };
  const stack = [];
  for (let i = open; i < text.length; i++) {
    const c = text[i];
    if (c === "/" && text[i + 1] === "/") {
      i = text.indexOf("\n", i);
    } else if (c === '"' || c === "'" || c === "`") {
      for (i++; text[i] !== c; i++) {
        if (i >= text.length) throw new Error("unterminated string");
        if (text[i] === "\\") i++;
      }
    } else if (pairs[c]) {
      stack.push(pairs[c]);
    } else if (c === stack[stack.length - 1]) {
      stack.pop();
      if (!stack.length) return text.slice(open, i + 1);
    }
  }
  throw new Error("unbalanced");
}

function after(text, marker) {
  const at = text.indexOf(marker);
  if (at < 0) throw new Error(`missing ${marker}`);
  return at + marker.length;
}

function bodyOf(text, signature) {
  const start = after(text, signature);
  return balanced(text, text.indexOf("{", start - 1)).slice(1, -1);
}

function property(text, name) {
  const start = after(text, `readonly property var ${name}:`);
  const open = text.slice(start).search(/[[{(]/) + start;
  const expr = balanced(text, open);
  // A property may continue with a method call, like `[...].map(...)`.
  const rest = text.slice(open + expr.length).match(/^\.map\(/) ? balanced(text, open + expr.length + 4) : "";
  return expr + (rest ? `.map${rest}` : "");
}

const blocks = bodyOf(editor, "function registerBlocks()");
const operators = bodyOf(registry, "function defaultOperators()");
const builtinIcons = balanced(registry, after(registry, "readonly property var builtinIcons: (") - 1);

// qsTr(...).arg(x) -> arg(qsTr(...), x), since qsTr returns a plain string here.
const deQt = (code) => code.replace(/qsTr\(("(?:[^"\\]|\\.)*")\)\.arg\(/g, "arg($1, ");

const out = `// Generated by scripts/extract-block-rows.mjs from Blockwork's EditorPage.qml
// and blockstitch's BlockRegistry.qml. Don't edit by hand; rerun the script.
// @ts-nocheck

const qsTr = (s) => s;
const arg = (s, v) => s.replace("%1", v);
const numberValue = (n) => ({ kind: "Number", value: n });
const textValue = (t) => ({ kind: "Text", value: t });
const firstGlobalName = () => "";
const appState = {};
const Qt = { formatDateTime: () => "" };
const Schedules = {
  dateTimeLabel: (t) => t, scheduleLabel: (t) => t, timeLabel: (t) => t,
  monthName: (m) => ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"][m - 1] ?? String(m),
};
const root = {
  macro: null,
  defaultDetector: "",
  choices: (pairs) => pairs.map((p) => ({ value: p[0], label: p[1] })),
  variableChoices: () => [],
  globalChoices: () => [],
  firstListName: () => "",
  otherMacroName: () => "",
};
root.mouseButtonOptions = ${deQt(property(editor, "mouseButtonOptions"))};
root.windowMatchOptions = ${deQt(property(editor, "windowMatchOptions"))};
root.imagePickOptions = ${deQt(property(editor, "imagePickOptions"))};
root.detectionSortOptions = ${deQt(property(editor, "detectionSortOptions"))};

export const ROWS: Record<string, any> = {};
export const OPERATORS: Record<string, any> = (() => {${deQt(operators)}})();
export const ICONS: Record<string, string> = { ...${builtinIcons} };
const hostDescriptors = [];
const BlockRegistry = {
  registerRows: (m) => Object.assign(ROWS, m),
  registerOperators: (m) => Object.assign(OPERATORS, m),
  registerIcons: (m) => Object.assign(ICONS, m),
  registerDescriptors: () => {},
  registerPrefabs: () => {},
};
(function registerBlocks() {${deQt(blocks)}})();
`;
writeFileSync("src/block-rows.ts", out);
console.log(`wrote src/block-rows.ts (${out.length} bytes)`);
